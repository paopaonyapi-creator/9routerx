// Package brand holds the passive origin canaries for 9RouterX: a small,
// self-contained record of where this tree came from. Nothing here phones
// home, crashes, or degrades anything. The package is deliberately not
// imported by the running app — it exists so a human (or
// tools/scripts/detect-derivative.sh) can prove a derivative tree's origin
// even after attribution headers are stripped and find&replace sweeps erase
// the account name from the sources.
//
// Deleting this file is safe by design: no code depends on it, and the list
// it embeds also ships as internal/brand/markerhash.txt, so the original
// repo can always recompute and compare the fingerprint.
package brand

import (
	"crypto/sha256"
	_ "embed"
	"encoding/base64"
	"encoding/hex"
	"strings"
)

//go:embed markerhash.txt
var markedFiles []byte // sorted repo-relative paths of every layer-1 marked file

// buildEpoch is stamped at release time via:
//
//	go build -ldflags "-X 9routerx/proxy/internal/brand.buildEpoch=<unix>"
//
// Untagged developer builds keep the empty default — which is itself part of
// the fingerprint (a build without the injection is distinguishable from one
// that carries it).
var buildEpoch = ""

// Attribution fragments. Deliberately split so no single find&replace of one
// string can rebuild the URL; several sibling sets live in the attribution.go
// files under internal/{config,proxy,telegram,handlers,semanticcache,updater,
// vault}. Joined only at runtime.
const (
	fragHost  = "github.com/"
	fragUserA = "yanstd"
	fragUserB = "888"
	fragName  = "9RouterX"
)

// Attribution line, base64-wrapped so text-level scrubbing cannot remove it
// together with the plain headers; decodeAttribution below is the only
// reader. (Content: "all source code port and modification by
// https://github.com/yanstd888/ — https://t.me/aiclub_id".)
const attributionB64 = "YWxsIHNvdXJjZSBjb2RlIHBvcnQgYW5kIG1vZGlmaWNhdGlvbiBieSBodHRwczovL2dpdGh1Yi5jb20veWFuc3RkODg4LyDigJQgaHR0cHM6Ly90Lm1lL2FpY2x1Yl9pZA=="

// Origin is the passive provenance record for this tree.
type Origin struct {
	Repo       string `json:"repo"`
	Channel    string `json:"channel"`
	BuildEpoch string `json:"buildEpoch,omitempty"`
	MarkerHash string `json:"markerHash"`
}

// decodeAttribution unwraps the base64 attribution line. Never fails hard:
// on any decode problem the wrapped literal itself comes back.
func decodeAttribution() string {
	raw, err := base64.StdEncoding.DecodeString(attributionB64)
	if err != nil {
		return attributionB64
	}
	return strings.TrimSpace(string(raw))
}

// SourceRepo joins the attribution fragments at runtime.
func SourceRepo() string {
	return "https://" + fragHost + fragUserA + fragUserB + "/" + fragName
}

// Attribution returns the decoded attribution line.
func Attribution() string { return decodeAttribution() }

// MarkerHash is the SHA256 of internal/brand/markerhash.txt — the sorted list
// of every file carrying a layer-1 attribution header, regenerated by
// tools/scripts/add-markers.sh. tools/scripts/detect-derivative.sh recomputes
// the same value over a suspect tree and compares.
func MarkerHash() string {
	sum := sha256.Sum256(markedFiles)
	return hex.EncodeToString(sum[:])
}

// MarkedFiles counts the entries in the embedded markerhash list.
func MarkedFiles() int {
	return strings.Count(strings.TrimSuffix(string(markedFiles), "\n"), "\n") + 1
}

// Get assembles the full origin record.
func Get() Origin {
	return Origin{
		Repo:       SourceRepo(),
		Channel:    "stable",
		BuildEpoch: buildEpoch,
		MarkerHash: MarkerHash(),
	}
}
